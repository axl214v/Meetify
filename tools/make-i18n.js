#!/usr/bin/env node
/**
 * Makes src/app/i18n/ru.js (what the browser loads) from src/app/i18n/ru.json (what people edit).
 *   node tools/make-i18n.js           write ru.js
 *   node tools/make-i18n.js --check   exit 1 if ru.js is missing or out of date
 */
'use strict';
const fs = require('fs');
const path = require('path');

const DIR = path.resolve(__dirname, '..', 'src', 'app', 'i18n');

function build() {
    const dict = JSON.parse(fs.readFileSync(path.join(DIR, 'ru.json'), 'utf8'));
    for (const [k, v] of Object.entries(dict)) {
        if (!(typeof v === 'string' || (Array.isArray(v) && v.length === 3 && v.every(x => typeof x === 'string')))) {
            throw new Error(`ru.json: the value of "${k}" must be a string or an array of three strings`);
        }
    }
    return '/* Generated by tools/make-i18n.js from ru.json. Do not edit. */\nwindow.__RU = ' + JSON.stringify(dict, null, 1) + ';\n';
}

if (require.main === module) {
    const out = path.join(DIR, 'ru.js');
    const text = build();
    if (process.argv.includes('--check')) {
        const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
        if (have !== text) { console.error('i18n/ru.js is out of date: run node tools/make-i18n.js'); process.exit(1); }
        console.log('i18n/ru.js is current');
    } else {
        fs.writeFileSync(out, text);
        console.log('wrote', path.relative(process.cwd(), out));
    }
}
module.exports = { build };
